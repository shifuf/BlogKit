// Keep the plain script used by the admin editor identical to the Nuxt player.
// Node 22.13+ supplies the TypeScript eraser; no bundler dependency is required.
import { readFile, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';

const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const unexport = source => source.replace(/^export\s+/gm, '');
const crypto = stripTypeScriptTypes(await read('frontend/utils/apiPayloadCrypto.ts'));
const fallback = await read('frontend/utils/musicSourceFallback.js');
const player = (await read('frontend/utils/plainMusicPlayer.js')).replace(/^import[^\n]+\n/gm, '');
const element = stripTypeScriptTypes(await read('frontend/utils/define-music-player.ts'))
  .replace(/^import\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*/gm, '');
const output = '// Generated by scripts/build-music-player.mjs; edit frontend/utils sources.\n(function(){\n'
  + [crypto, fallback, player, element].map(unexport).join('\n')
  + '\nwindow.createPlainMusicPlayer = createPlainMusicPlayer;\nwindow.PLAYER_LAYOUT_VERSION = PLAYER_LAYOUT_VERSION;\ndefineMusicPlayerElement();\n})();\n';
for (const path of ['dashboard/public/music-player.js', 'frontend/public/music-player.js']) {
  await writeFile(new URL(path, root), output, 'utf8');
}
console.log('Regenerated admin and public music players from shared sources.');
