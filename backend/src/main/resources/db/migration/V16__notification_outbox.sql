CREATE TABLE notification_outbox (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind VARCHAR(16) NOT NULL,
 article_id BIGINT REFERENCES article(id) ON DELETE CASCADE,
 subscriber_id BIGINT REFERENCES email_subscription(id) ON DELETE CASCADE,
 recipient VARCHAR(255) NOT NULL, subject VARCHAR(300) NOT NULL, body TEXT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING', attempts INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 locked_until TIMESTAMPTZ, sent_at TIMESTAMPTZ,last_error VARCHAR(500)
);
CREATE UNIQUE INDEX uq_outbox_article_recipient ON notification_outbox(article_id,subscriber_id,kind) WHERE kind='ARTICLE';
CREATE INDEX idx_outbox_pending ON notification_outbox(status,next_attempt_at);
ALTER TABLE email_subscription ADD COLUMN confirmation_token_hash VARCHAR(64);
ALTER TABLE email_subscription ADD COLUMN confirmation_expires_at TIMESTAMPTZ;
ALTER TABLE email_subscription ALTER COLUMN confirmed SET DEFAULT FALSE;
ALTER TABLE email_subscription ALTER COLUMN enabled SET DEFAULT FALSE;
-- Historical subscriptions did not prove ownership. Require a fresh opt-in, retaining the rows.
UPDATE email_subscription SET confirmed=FALSE,enabled=FALSE WHERE confirmed=TRUE;
CREATE UNIQUE INDEX uq_subscription_confirmation ON email_subscription(confirmation_token_hash) WHERE confirmation_token_hash IS NOT NULL;
