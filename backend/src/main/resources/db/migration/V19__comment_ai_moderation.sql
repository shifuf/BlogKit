-- Bring legacy counters into agreement with the public visibility rules.
UPDATE dynamic_comment root SET reply_count=(
    SELECT count(*) FROM dynamic_comment r WHERE r.parent_id=root.id AND r.visible AND r.status='APPROVED'
) WHERE root.parent_id IS NULL;
UPDATE dynamic_post p SET comment_count=(
    SELECT count(*) FROM dynamic_comment c LEFT JOIN dynamic_comment root ON root.id=c.parent_id
    WHERE c.dynamic_id=p.id AND c.visible AND c.status='APPROVED'
    AND (c.parent_id IS NULL OR (root.visible AND root.status='APPROVED'))
);
UPDATE article a SET comment_count=(
    SELECT count(*) FROM article_comment c LEFT JOIN article_comment root ON root.id=c.parent_id
    WHERE c.article_id=a.id AND (c.status IS NULL OR c.status='APPROVED')
    AND (c.parent_id IS NULL OR root.status IS NULL OR root.status='APPROVED')
);

-- No comment bodies or credentials are stored in the queue. Kind + ID is an idempotency key.
CREATE TABLE comment_ai_review (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind varchar(16) NOT NULL CHECK (kind IN ('ARTICLE','DYNAMIC')),
    comment_id bigint NOT NULL,
    state varchar(16) NOT NULL DEFAULT 'PENDING'
        CHECK (state IN ('PENDING','RUNNING','DONE','FAILED','CANCELLED')),
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    lease_token varchar(36),
    lease_until timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(kind, comment_id)
);
CREATE INDEX idx_comment_ai_review_due ON comment_ai_review(state, next_attempt_at, lease_until);

