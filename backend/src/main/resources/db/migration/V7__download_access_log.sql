-- 下载打开统计
create table if not exists download_access_log (
    id bigint generated by default as identity primary key,
    article_id bigint,
    kind varchar(32) not null,
    gate varchar(32) not null,
    title varchar(120),
    client_ip varchar(64),
    created_at timestamp(6) with time zone not null
);

create index if not exists idx_download_access_created on download_access_log (created_at);
create index if not exists idx_download_access_article on download_access_log (article_id, created_at);
